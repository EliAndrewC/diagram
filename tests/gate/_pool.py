"""THE GATE READS THE POOL'S MAPS (feature 215, GM 2026-09-08).

The reference and Kuwabata are shipped maps: the pool sweep rolls each in a coverage child when its cache key
moved and serves it from the gen cache otherwise, and its manifest is on disk. Until this feature the gate rolled
both AGAIN under specs of their own - the audit (specs/215 research R1) found those rolls reached no engine line
the sweep's children do not. So every gate reader of those two specs comes here: `rolled_map(spec)` is the plan
and the manifest, `rolled_report(spec)` the Report the ratchet judges - both read back from the pool's map, whose
meta carries the roll's own verdict since D3. Any other spec goes to the roll cache as before, so the callers
need not know which kind they hold.

ONE OBTAIN AT A TIME PER GEN: fifteen gate modules ask for the reference at t=0 in six workers, and a cold
`gate_obtain` regenerates on a MISS - six workers arriving together would regenerate six times (the census would
fail the gate: a pool gen rolled more than once). The first-wave lock of the roll cache serializes them; the
second worker's obtain is a HIT on the entry the first published.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

import pytest

from l7r.diagram import hamletgen as hg
from l7r.diagram import switches
from l7r.diagram.pipeline import gencache, rollcache

HERE = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
POOL: dict[tuple[str, int], str] = {
    ("Inashiro", 4): "pool/hamlets/inashiro/inashiro.gen.py",
    ("Kuwabata", 21): "pool/hamlets/kuwabata/kuwabata.gen.py",
}


def python_maps_off() -> bool:
    """Is the port switch at `rust-only` (feature 444 FR-023)?"""
    return switches.read(Path(HERE)).port.state == "rust-only"


def no_python_map() -> None:
    """AT `rust-only` NO PYTHON MAP IS ROLLED OR READ (the GM 2026-11-07: "You should immediately stop running all of the python
    map generating code as well. That's only slowing us down."): every pool map and roll-cache map a test asks is skipped, never
    regenerated - measured the same day, tests the `rolls_map` marker misses (they reach a map through this module) rolled
    Inashiro, Kashikawa, Kuwabata and Mizuguchi again in a run meant to roll none, and rewrote their maps on disk."""
    if python_maps_off():
        pytest.skip("the port at rust-only: no Python map is rolled or read (feature 444 FR-023)")


def gen_of(spec: hg.HamletSpec) -> str | None:
    """The shipped generator of `spec`, or None for a spec the pool does not carry."""
    rel = POOL.get((spec.name, spec.seed))
    return os.path.join(HERE, rel) if rel else None


def obtain_full(gen: str) -> tuple[str, str, float | None]:
    """`gate_obtain`'s own triple, taken under the run's per-gen lock.

    EVERY READER OF A SHIPPED GENERATOR COMES THROUGH HERE, THE POOL SWEEP INCLUDED (feature 229).
    The lock is what makes "a spec is rolled once per gate" true of a COLD cache: `gate_obtain`
    regenerates on a miss, so two callers that reach it together each roll the same map and the
    census fails the gate. The sweep (`tests/test_villages.py::_regen_and_gate`) used to call
    `gencache.gate_obtain` directly and so took no lock, which is invisible while the cache is warm
    and fires the moment a merge moves a generator's key - measured on Kuwabata after feature 228
    landed, rolled twice in one run, by the sweep and by the lateral test.
    """
    no_python_map()
    share = rollcache._run_share_path(("pool", gen))
    with rollcache._share_lock(share):
        if gen in _OBTAINED:  # ...ONCE A TEST (feature 417 T44, the round arbiter's tooling fix on
            # ask:417-T31-C2-regression): a stale map regenerated by one read was regenerated AGAIN by the next read in the
            # same test (`rolled_map` then `rolled_report`), and the census refused an otherwise-green landing
            return _OBTAINED[gen][0], "CACHED", _OBTAINED[gen][2]
        # ...AND A REFUSED ROLL ONCE A RUN (feature 444 T16's gate): a map a later Python stage refuses until its port (Sawada's
        # house seating, held as strict xfails, `tests/_waiting_ports.py`) wrote no manifest to share, so each of its twelve
        # readers rolled it again and the census failed the gate. The refusal is shared like the manifest, and re-raised.
        refused = share + ".refused" if share else None
        if refused and os.path.exists(refused):
            with open(refused, encoding="utf-8") as fh:
                raise RuntimeError(f"{gen} was refused earlier in this run, not rolled again: {fh.read()}")
        try:
            manifest, how, cpu_s = gencache.gate_obtain(gen)
        except Exception as e:
            if refused:
                with open(refused, "w", encoding="utf-8") as fh:
                    fh.write(f"{type(e).__name__}: {e}")
            raise
        if how == "REGENERATED":
            refresh_census(manifest)
        _OBTAINED[gen] = (manifest, how, cpu_s)
        return manifest, how, cpu_s


_OBTAINED: dict[str, tuple[str, str, float | None]] = {}
"""The pool maps this test has already obtained, each read once (`obtain_full`); emptied before every test
(`tests/conftest.py`), so a test that stubs the generator still sees each of its own reads."""


def refresh_census(manifest: str) -> bool:
    """A regenerated map's notes census block rewritten from its new manifest, under the same lock (the GM 2026-10-24: T26's
    landing regenerated three pool farms, and the same gate run's `tests/test_notes_census.py` failed their stale census -
    five minutes of gate for `make notes-census`, which a session ran by hand after). True where the notes changed; the landing
    commits them with the regenerated maps (`land.commit_regenerated`, everything under `pool/`)."""
    from l7r.diagram.tools import notes_census

    notes = manifest[: -len(".json")] + ".notes.md"
    if not os.path.exists(notes):
        return False
    with open(manifest, encoding="utf-8") as fh:
        M = json.load(fh)
    with open(notes, encoding="utf-8") as fh:
        text = fh.read()
    new = notes_census.replace(text, M)
    if new == text:
        return False
    with open(notes, "w", encoding="utf-8") as fh:
        fh.write(new)
    return True


def obtain(gen: str) -> str:
    """The pool map's manifest path, through the gen cache under the run's per-gen lock."""
    manifest, _how, _cpu = obtain_full(gen)
    return manifest


def rolled_map(spec: hg.HamletSpec) -> tuple[Any, dict[str, Any]]:
    """`(plan, manifest)` of `spec` - the pool's map for a shipped spec, the roll cache's for any other."""
    gen = gen_of(spec)
    if gen is None:
        no_python_map()
        return rollcache.hamlet(spec)
    with open(obtain(gen), encoding="utf-8") as fh:
        M: dict[str, Any] = json.load(fh)
    plan = hg.plan_site(spec)
    meta = M.get("meta") or {}
    plan.placed = int(meta.get("roll_placed", len(M.get("houses", []))))
    plan.acres = float(meta.get("roll_acres", 0.0))
    return plan, M


def rolled_report(spec: hg.HamletSpec) -> hg.Report:
    """The Report of `spec`'s roll - read back from the pool map's meta for a shipped spec (D3)."""
    if gen_of(spec) is None:
        no_python_map()
        return rollcache.report(spec)[0]
    plan, M = rolled_map(spec)
    return hg.Report(plan=plan, failures=[], manifest=M)
