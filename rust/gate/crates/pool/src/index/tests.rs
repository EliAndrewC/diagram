/// Every map has its row, of whatever kind - the hamlets, the frozen exhibits and the unclassified included - grouped by tree and tier,
/// its name linking its page where its folder holds one, and its picture, drawing and notes beside it.
#[test]
fn every_map_has_a_row_linking_what_its_folder_holds() {
    let root = fixture("index-rows");
    let mut w = walk(&root);
    let html = page(&mut w);
    assert_eq!(html.matches("<li>").count(), w.maps.len());
    assert!(html.contains("<p>7 maps: 5 in the live pool, 2 in the frozen exhibits."));
    assert!(html.contains("<p class=\"muted\">3 folders the walk could not classify"));
    assert!(html.contains(
        "<h2>Live pool<span class=\"where\">pool/ - regenerated by their engines</span></h2>"
    ));
    assert!(html.contains("<h3>magistracies<span class=\"where\">2 maps</span></h3>"));
    assert!(html.contains("<h3>towns<span class=\"where\">1 map</span></h3>"));
    // a page: the name links it; a picture beside it, the drawing left out where the picture stands for it
    assert!(html.contains(
        "<li><a class=\"name\" href=\"magistracies/h/h.html\">h</a> <span class=\"kind\">hand sheet</span> <span class=\"links\"><a href=\"magistracies/h/h.png\">picture</a></span></li>"
    ));
    // no page: said, and the drawing linked
    assert!(html.contains(
        "<li><span class=\"name\">c</span> <span class=\"kind\">generated compound</span> <span class=\"links\"><span class=\"muted\">no rendered page</span> &middot; <a href=\"magistracies/c/c.svg\">drawing</a></span></li>"
    ));
    // a hamlet: the Rust driver's drawing
    assert!(html.contains("<span class=\"name\">a</span> <span class=\"kind\">hamlet</span> <span class=\"links\"><span class=\"muted\">no rendered page</span> &middot; <a href=\"hamlets/a/a.driver.svg\">driver drawing</a> &middot; <a href=\"hamlets/a/a.notes.md\">notes</a></span>"));
    // the frozen exhibits link out of pool/
    assert!(html.contains(
        "<span class=\"kind\">frozen exhibit</span> <span class=\"links\"><span class=\"muted\">no rendered page</span> &middot; <a href=\"../legacy-hand-authored-pool/villages/v/v.notes.md\">notes</a></span>"
    ));
    assert!(html.contains("<span class=\"name\">u</span> <span class=\"kind\">unclassified</span>"));
    assert!(html.ends_with("</ul>\n</main>\n</body>\n</html>\n"));
}

/// A hamlet's row links only what the Rust driver writes (feature 449 T222): a `.png`, `.html` or `.svg` beside its spec is the deleted
/// Python engine's last picture, page or drawing (444 T39), stale since, which main's hamlets still held - linked, it showed the GM a
/// map no engine draws as the hamlet's own.
#[test]
fn a_hamlet_links_the_driver_s_drawing_never_the_python_s_leftovers() {
    let root = fixture("index-leftovers");
    for end in [".png", ".html", ".svg"] {
        put(&root, &format!("pool/hamlets/a/a{end}"), "x");
    }
    let html = page(&mut walk(&root));
    assert!(html.contains("<li><span class=\"name\">a</span> <span class=\"kind\">hamlet</span> <span class=\"links\"><span class=\"muted\">no rendered page</span> &middot; <a href=\"hamlets/a/a.driver.svg\">driver drawing</a> &middot; <a href=\"hamlets/a/a.notes.md\">notes</a></span></li>"));
    assert!(
        !html.contains("hamlets/a/a.html")
            && !html.contains("hamlets/a/a.png")
            && !html.contains("hamlets/a/a.svg\"")
    );
}

/// A tree with no maps says so; one map is "1 map"; a name is escaped; nothing unclassified, nothing said of it.
#[test]
fn an_empty_tree_says_so_and_a_name_is_escaped() {
    let root = l7r_shared::tempdir::TempDir::new("pool-index-empty");
    put(&root, crate::DECLARATION, "[]");
    put(&root, "pool/hamlets/a&b/a&b.spec.json", "x");
    let mut w = walk(&root);
    let html = page(&mut w);
    assert!(html.contains("<p>1 map: 1 in the live pool, 0 in the frozen exhibits."));
    assert!(html.contains("<span class=\"name\">a&amp;b</span>"));
    assert!(html.contains(&format!("<h2>Frozen exhibits<span class=\"where\">{LEGACY}/ - hand-authored, kept as they are</span></h2>\n<p class=\"muted\">No maps.</p>")));
    assert!(!html.contains("could not classify"));
    assert_eq!(super::escape("<\"x\">"), "&lt;&quot;x&quot;&gt;");
}

/// The page is written where it differs and left alone where it does not; the same pool composes the same page.
#[test]
fn the_index_is_written_only_when_it_differs() {
    let root = fixture("index-write");
    assert!(write(&root, &mut walk(&root)).unwrap());
    let first = std::fs::read_to_string(root.join(INDEX)).unwrap();
    assert_eq!(first, page(&mut walk(&root)));
    assert!(!write(&root, &mut walk(&root)).unwrap());
    assert!(!compare(&root, &mut walk(&root)).1);
    put(&root, "pool/magistracies/c/c.html", "x");
    assert!(compare(&root, &mut walk(&root)).1);
    assert!(write(&root, &mut walk(&root)).unwrap());
    assert!(std::fs::read_to_string(root.join(INDEX))
        .unwrap()
        .contains("href=\"magistracies/c/c.html\""));
    // no temporary file is left
    assert_eq!(std::fs::read_dir(root.join("pool")).unwrap().count(), 5);
}

/// A page that cannot be written (no pool/), or not renamed into place, is an error, and leaves no temporary file.
#[test]
fn an_index_that_cannot_be_written_is_an_error() {
    let root = l7r_shared::tempdir::TempDir::new("pool-index-nowhere");
    assert!(write(&root, &mut walk(&root)).is_err());
    let root = fixture("index-blocked");
    put(&root, "pool/index.html/in-the-way", "x");
    assert!(write(&root, &mut walk(&root)).is_err());
    assert!(std::fs::read_dir(root.join("pool"))
        .unwrap()
        .flatten()
        .all(|e| !e.file_name().to_string_lossy().contains(".tmp")));
}

/// One `index_row` a map, charged to its tree.
#[cfg(feature = "counters")]
#[test]
fn each_row_is_counted_to_its_tree() {
    let root = fixture("index-counts");
    let mut w = walk(&root);
    let _ = page(&mut w);
    assert!(w.counts.of(crate::LIVE).contains(&("index_row", 5)));
    assert!(w.counts.of(LEGACY).contains(&("index_row", 2)));
}

/// THE REAL POOL'S INDEX LISTS EVERY MAP (T220): one row a map folder of either tree, each named. The page `make pool-index` wrote
/// before linked 6 of the 30 maps, the six Mode A sheets (a measurement of that page on 2026-11-19, not a run of this test).
#[test]
fn the_real_pools_index_lists_every_map_of_both_trees() {
    let tree = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../..");
    let mut w = walk(&tree);
    let html = page(&mut w);
    assert_eq!(html.matches("<li>").count(), w.maps.len());
    assert!(w.maps.len() >= 30);
    for m in &w.maps {
        // the folder rides in the compared value, so a failure names it
        assert_eq!(
            (m.rel(), html.contains(&format!(">{}</", m.name))),
            (m.rel(), true)
        );
    }
}
