//! A map's canonical counts, in a block its `.notes.md` carries (feature 449 T170): `l7r/diagram/tools/notes_census.py` ported and
//! deleted, `make notes-census` running [`main`].
//!
//! WHY IT EXISTS (the Python's, feature 152): three times running a settlement-review caught a notes paragraph asserting counts the
//! shipping roll contradicted, typed by hand from a measurement taken before the last re-roll. So the counts a notes file states are
//! DERIVED: `make notes-census` writes them into a marked block; prose around the block stays the author's. A notes file with no block is
//! not required to grow one.
//!
//! Every line, refusal and exit is the Python's (FR-002): a manifest's value is read as Python read what `json.load` made of it
//! (`x or []`, `str()`, `len()`, `float()`), and an uncaught exception ends the run with its traceback's last line and exit 1, the files
//! rewritten before it left rewritten.
